def process_image(input_img, color_mode, kernel_size, kernel_str, do_normalize, confidence_upsample):
    if input_img is None:
        return "請上傳影像", None, None, None, "N/A", None, "0"

    # --- 功能 1：影像載入與中繼資訊 ---
    h, w, c = input_img.shape
    file_size_approx = input_img.nbytes / 1024
    metadata = f"**解析度:** {w} × {h} 像素\n**色彩維度:** {c} 通道\n**圖像記憶體占用:** {file_size_approx:.2f} KB"

    # --- 功能 2：多色彩空間轉換與直方圖 ---
    if color_mode == "Original":
        disp_img = input_img
    elif color_mode == "R Channel":
        disp_img = np.stack([input_img[:, :, 0]]*3, axis=-1)
    elif color_mode == "G Channel":
        disp_img = np.stack([input_img[:, :, 1]]*3, axis=-1)
    elif color_mode == "B Channel":
        disp_img = np.stack([input_img[:, :, 2]]*3, axis=-1)
    else:
        # 純 NumPy YUV 轉換矩陣
        R, G, B = input_img[:,:,0].astype(float), input_img[:,:,1].astype(float), input_img[:,:,2].astype(float)
        Y = (0.299 * R + 0.587 * G + 0.114 * B).astype(np.uint8)
        U = (-0.14713 * R - 0.28886 * G + 0.436 * B + 128).astype(np.uint8)
        V = (0.615 * R - 0.51499 * G - 0.10001 * B + 128).astype(np.uint8)

        selected = Y if "Y" in color_mode else (U if "U" in color_mode else V)
        disp_img = np.stack([selected]*3, axis=-1)

    hist_fig = plot_histogram(disp_img, color_mode)

    # --- 功能 3：自訂卷積核空間濾波與 PSNR ---
    kernel, err_msg = parse_kernel_string(kernel_str, int(kernel_size))
    if kernel is None:
        filtered_img = input_img
        psnr_text = f"錯誤: {err_msg}"
    else:
        k_sum = np.sum(kernel)
        if do_normalize and k_sum != 0:
            kernel = kernel / k_sum

        filtered_img = apply_convolution(input_img, kernel)
        psnr_val = calculate_psnr(input_img, filtered_img)
        psnr_text = f"{psnr_val:.2f} dB" if psnr_val != float('inf') else "∞ (無失真)"

    # --- 功能 4：人臉偵測模組 (HOG 特徵檢測器) ---
    # face_recognition.face_locations 回傳 [(top, right, bottom, left), ...]
    face_locations = face_recognition.face_locations(input_img, number_of_times_to_upsample=int(confidence_upsample), model="hog")
    face_count = len(face_locations)

    # 在圖片上繪製正確認出的人臉框
    pil_face = Image.fromarray(input_img.copy())
    draw = ImageDraw.Draw(pil_face)

    for (top, right, bottom, left) in face_locations:
        draw.rectangle([left, top, right, bottom], outline="lime", width=3)
        draw.text((left, max(0, top - 15)), "Face (HOG)", fill="lime")

    face_img_out = np.array(pil_face)

    return metadata, disp_img, hist_fig, filtered_img, psnr_text, face_img_out, f"{face_count} 人"

