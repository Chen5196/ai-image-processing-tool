# 1. 核心演算法定義 (PSNR, Kernel 空間域濾波, 直方圖)
# -----------------------------------------------------------------------------

def calculate_psnr(img1, img2):
    """計算 PSNR (Peak Signal-to-Noise Ratio)"""
    mse = np.mean((img1.astype(np.float64) - img2.astype(np.float64)) ** 2)
    if mse == 0:
        return float('inf')
    max_pixel = 255.0
    return 20 * np.log10(max_pixel / np.sqrt(mse))

def parse_kernel_string(kernel_str, size):
    """解析使用者輸入的矩陣字串，並做防呆驗證"""
    try:
        lines = [line.strip() for line in kernel_str.strip().split('\n') if line.strip()]
        matrix = [list(map(float, line.split(','))) for line in lines]
        kernel = np.array(matrix, dtype=np.float32)
        if kernel.shape != (size, size):
            return None, f"維度不符：預期 {size}x{size}，但輸入為 {kernel.shape[0]}x{kernel.shape[1]}"
        return kernel, None
    except Exception as e:
        return None, f"矩陣解析失敗：{str(e)}"

def apply_convolution(img_np, kernel):
    """純 NumPy 實作 2D 空間域卷積濾波 (支援 3x3 與 5x5)"""
    kh, kw = kernel.shape
    pad_h, pad_w = kh // 2, kw // 2

    padded = np.pad(img_np, ((pad_h, pad_h), (pad_w, pad_w), (0, 0)), mode='edge')
    output = np.zeros_like(img_np, dtype=np.float32)

    for i in range(kh):
        for j in range(kw):
            output += padded[i:i+img_np.shape[0], j:j+img_np.shape[1], :] * kernel[i, j]

    return np.clip(output, 0, 255).astype(np.uint8)

def plot_histogram(img_np, mode):
    """動態繪製直方圖 (橫軸 0-255，縱軸像素數量)"""
    fig, ax = plt.subplots(figsize=(6, 3))
    if len(img_np.shape) == 3 and mode == "Original":
        colors = ('red', 'green', 'blue')
        for i, col in enumerate(colors):
            hist, _ = np.histogram(img_np[:, :, i], bins=256, range=(0, 256))
            ax.plot(hist, color=col, label=f'{col.upper()} Channel')
        ax.legend()
    else:
        gray_flat = img_np[:, :, 0].ravel() if len(img_np.shape) == 3 else img_np.ravel()
        hist, _ = np.histogram(gray_flat, bins=256, range=(0, 256))
        ax.plot(hist, color='black')

    ax.set_title(f"Histogram ({mode})")
    ax.set_xlim([0, 256])
    ax.set_xlabel("Pixel Intensity (0-255)")
    ax.set_ylabel("Pixel Count")
    plt.tight_layout()
    return fig

